#!/usr/bin/env python3
"""Write weave/data.js: a few real weave cycles for the How to weave animation.

Each variant is one iteration of the SV Weave preset with its rotation (max weave = default.apl.siml, normal weave =
normal_weave.apl.siml), simmed with the debug log on: two single sims, one iteration each. From the log it keeps a
steady stretch of the fight that starts and ends standing at the shooting spot, with the walks, Auto Shot's windups
and shots, the two-hander's swings (and when each swing was ready) and the rotation's casts.

    python3 tools/build_weave_demo.py --forever ~/forever --cli /tmp/hg/wowsimcli
    python3 tools/build_weave_demo.py --logs /tmp/hg        # reuse log_default.txt and log_normal_weave.txt
"""
import argparse, copy, json, os, re, subprocess

VARIANTS = {'max': ('default', 3), 'normal': ('normal_weave', 2)}  # rotation file, cycles to keep
FROM = 20.0  # skip the opener

NAMES = {
    'OtherID: 4': 'Auto Shot', 'OtherID: 3, Tag: 14': 'Swing', 'SpellID: 14266': 'Raptor Strike',
    'SpellID: 1317257': 'Strider Kick', 'SpellID: 14271': 'Mongoose Bite', 'SpellID: 14305': 'Immolation Trap',
    'SpellID: 14268': 'Wing Clip', 'SpellID: 13555': 'Serpent Sting', 'SpellID: 14287': 'Arcane Shot',
    'SpellID: 2643': 'Multi-Shot', 'SpellID: 20904': 'Aimed Shot', 'SpellID: 3045': 'Rapid Fire',
    'SpellID: 14325': "Hunter's Mark", 'SpellID: 20572': 'Racial', 'ItemID: 250943': 'Major Frenzy Potion',
}
LINE = re.compile(r'^\[(-?[\d.]+)\] \[ \(#1\)\] (.*)$')
TARGET_LINE = re.compile(r'^\[(-?[\d.]+)\] \[ \(#1\)\] \[Target 1\] \{(.*?)\} (Hit|Crit|Miss|Dodge|Parry|Glance|Block)\b')
DUR = re.compile(r'([\d.]+)(µs|ms|s)')


def seconds(text):
    m = DUR.fullmatch(text)
    if not m:
        return 0.0
    return float(m.group(1)) * {'µs': 1e-6, 'ms': 1e-3, 's': 1.0}[m.group(2)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--forever', default=os.path.expanduser('~/forever'))
    ap.add_argument('--cli', default=None)
    ap.add_argument('--logs', default=None, help='a folder with log_<rotation>.txt to reuse instead of simming')
    ap.add_argument('--out', default='weave/data.js')
    a = ap.parse_args()
    out = {}
    for key, (apl, cycles) in VARIANTS.items():
        text = open(os.path.join(a.logs, f'log_{apl}.txt')).read() if a.logs else sim_log(a, apl)
        out[key] = extract(text, cycles)
        print(key, out[key]['window'], len(out[key]['events']), 'events')
    with open(a.out, 'w') as f:
        f.write('// Generated by tools/build_weave_demo.py from one iteration of each weave rotation. Do not edit by hand.\n')
        f.write('window.WEAVE = ')
        json.dump(out, f, separators=(',', ':'))
        f.write(';\n')


def sim_log(a, apl):
    """One iteration of the SV Weave preset over defaults.siml with this rotation, the debug log on."""
    cli = os.path.abspath(a.cli or os.path.join(a.forever, 'bin/wowsimcli'))
    d = os.path.join(a.forever, 'ui/specs/hunter/dps')
    parse = lambda path: json.loads(subprocess.run([cli, 'siml', 'parse', '-json', path], capture_output=True, text=True, check=True).stdout)
    s = copy.deepcopy(parse(f'{d}/defaults.siml'))
    for k, v in parse(f'{d}/builds/sv_weave.siml')['player'].items():
        if k != 'rotation':
            s['player'][k] = v
    rot = parse(f'{d}/apls/{apl}.apl.siml')
    s['player']['rotation'] = rot.get('player', {}).get('rotation') or rot.get('rotation') or rot
    req = {'raid': {'parties': [{'players': [s['player']]}, {}, {}, {}, {}], 'buffs': s.get('raidBuffs', {}), 'debuffs': s.get('debuffs', {})},
           'encounter': s['encounter'], 'simOptions': {'iterations': 1, 'randomSeed': 1, 'debug': True}, 'type': 'SimTypeIndividual'}
    tmp = f'/tmp/weave_demo_{apl}'
    json.dump(req, open(tmp + '.json', 'w'))
    subprocess.run([cli, 'sim', '--infile', tmp + '.json', '--outfile', tmp + '.out.json'], check=True, capture_output=True, cwd=a.forever)
    return json.load(open(tmp + '.out.json'))['logs']


def extract(text, cycles):
    legs, stops, casts, results, ready, lit = [], [], [], [], {}, []
    for raw in text.splitlines():
        m = TARGET_LINE.match(raw)
        if m:
            results.append((float(m.group(1)), m.group(2), m.group(3)))
            continue
        m = LINE.match(raw)
        if not m:
            continue
        t, msg = float(m.group(1)), m.group(2)
        if w := re.match(r'Walking from ([\d.]+) to ([\d.]+) yards over (\S+)$', msg):
            if legs and legs[-1]['e'] > t:  # a new walk (a speed change) ends the one under way where it stands
                legs[-1].update(e=t, to=float(w.group(1)))
            legs.append({'s': t, 'e': t + seconds(w.group(3)), 'from': float(w.group(1)), 'to': float(w.group(2))})
        elif w := re.match(r'Stopped walking at ([\d.]+) yards', msg):
            stops.append((t, float(w.group(1))))
            if legs and legs[-1]['e'] > t:
                legs[-1].update(e=t, to=float(w.group(1)))
        elif c := re.match(r'Casting \{(.*?)\} \(Cost = [^,]*, Cast Time = (\S+), GCD = (\S+),', msg):
            casts.append({'t': t, 'id': c.group(1), 'cast': seconds(c.group(2)), 'gcd': seconds(c.group(3))})
        elif d := re.match(r'\{(.*?)\} delayed by \S+, was ready at ([\d.]+)s', msg):
            ready[(d.group(1), round(t, 2))] = float(d.group(2))
        elif msg == 'Aura gained: {SpellID: 1310726}':  # Expose Prey: Mongoose Bite is lit
            lit.append([t, None])
        elif msg == 'Aura faded: {SpellID: 1310726}' and lit and lit[-1][1] is None:
            lit[-1][1] = t
    # The window: from standing at the shooting spot after FROM s, through `cycles` trips into melee and back.
    far = [round(y, 2) for t, y in stops if t >= FROM and y > 11.67]
    shoot = max(set(far), key=far.count)  # where the hunter stands to shoot, past the dead zone
    at_spot = [t for t, y in stops if abs(y - shoot) < 0.05 and t >= FROM]
    melee_visits = [t for t, y in stops if y <= 5.0]
    start = at_spot[0]
    ends = [t for t in at_spot if sum(1 for v in melee_visits if start < v < t) >= cycles]
    end = ends[0]

    def pos_at(t):
        y = shoot
        for leg in legs:
            if leg['s'] > t:
                break
            span = leg['e'] - leg['s']
            if t >= leg['e'] or span <= 0:
                y = leg['to'] if t >= leg['e'] else leg['from']
            else:
                y = leg['from'] + (leg['to'] - leg['from']) * (t - leg['s']) / span
        return y

    rel = lambda t: round(t - start, 3)
    win_legs = [{'s': rel(l['s']), 'e': rel(l['e']), 'from': round(l['from'], 2), 'to': round(l['to'], 2)}
                for l in legs if l['e'] > start and l['s'] < end]
    events = []
    swings = []
    for c in casts:
        name = NAMES.get(c['id'])
        if not name or c['t'] < start - 4 or c['t'] > end:
            continue
        ev = {'t': rel(c['t']), 'name': name, 'cast': round(c['cast'], 3), 'gcd': round(c['gcd'], 2)}
        if name in ('Swing', 'Raptor Strike') and c['id'] != 'SpellID: 14266, Tag: 1':
            r = ready.get((c['id'], round(c['t'], 2)))
            ev['swing'] = True
            if r is not None:
                ev['ready'] = rel(r)
            swings.append(c['t'])
        if name == 'Auto Shot':
            r = ready.get(('OtherID: 4', round(c['t'], 2)))
            if r is not None:
                ev['ready'] = rel(r)
        out = next((o for (rt, rid, o) in results if rid == c['id'] and c['t'] <= rt <= c['t'] + c['cast'] + 1.2), None)
        if out:
            ev['out'] = out
        events.append(ev)
    events.sort(key=lambda e: e['t'])
    mongoose_lit = [[rel(s), rel(e if e is not None else end)] for s, e in lit if (e is None or e > start - 6) and s < end]
    return {'window': [round(start, 2), round(end, 2)], 'duration': rel(end), 'shootSpot': round(shoot, 2),
            'startYards': round(pos_at(start), 2), 'legs': win_legs, 'events': events, 'mongooseLit': mongoose_lit}


if __name__ == '__main__':
    main()
