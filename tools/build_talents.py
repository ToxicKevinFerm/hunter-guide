#!/usr/bin/env python3
"""Write guide/data/talents.js: the hunter's three talent trees from Wowhead's Forever talent calculator.

Each talent keeps its row, column, ranks, icon, the description of every rank and its prerequisite. The trees are in
the sim's order (Beast Mastery, Marksmanship, Survival) and each tree's talents row by row, column by column, which is
the order of the digits in a talent string. With --forever the trees are checked against the sim's own
ui/sim/talents/trees/hunter.json (names, positions, ranks).

    python3 tools/build_talents.py [--forever ~/forever] [--out guide/data/talents.js]
"""
import argparse, json, os, re, urllib.request

URL = 'https://nether.wowhead.com/forever/data/talents-classic'
TREES = [('361', 'Beast Mastery', 'bm'), ('363', 'Marksmanship', 'mm'), ('362', 'Survival', 'sv')]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--forever', default=None)
    ap.add_argument('--out', default='guide/data/talents.js')
    a = ap.parse_args()

    req = urllib.request.Request(URL, headers={'User-Agent': 'hunter-guide build_talents'})
    text = urllib.request.urlopen(req).read().decode('utf-8')
    start = text.index('{', text.index('setPageData('))
    data, _ = json.JSONDecoder().raw_decode(text, start)

    trees = []
    for tab, name, key in TREES:
        raw = sorted(data['talents'][tab].values(), key=lambda t: (t['row'], t['col']))
        pos = {t['id']: (t['row'], t['col']) for t in raw}
        talents = []
        for t in raw:
            req_ = t['requires'][0] if t['requires'] else None
            talents.append({
                'row': t['row'], 'col': t['col'], 'max': len(t['ranks']), 'name': t['name'], 'icon': t['icon'],
                'spell': t['ranks'][0], 'ranks': [clean(t['descriptions'][str(r + 1)]) for r in range(len(t['ranks']))],
                'req': {'row': pos[req_['id']][0], 'col': pos[req_['id']][1], 'qty': req_['qty']} if req_ else None,
                'reqPoints': t['requiredPoints'],
            })
        trees.append({'key': key, 'name': name,
                      'bg': f'https://wow.zamimg.com/images/wow/talents/backgrounds/tbc/{tab}.jpg', 'talents': talents})

    if a.forever:
        check(trees, os.path.join(a.forever, 'ui/sim/talents/trees/hunter.json'))

    with open(a.out, 'w') as f:
        f.write('// Generated by tools/build_talents.py from Wowhead\'s Forever talent calculator. Do not edit by hand.\n')
        f.write('window.TALENTS = ')
        json.dump({'hashVersion': data['hashVersion'], 'trees': trees}, f, separators=(',', ':'), ensure_ascii=False)
        f.write(';\n')
    print(a.out, data['hashVersion'], [len(t['talents']) for t in trees])


def clean(s):
    return re.sub(r'\s+', ' ', s).strip()


def check(trees, path):
    sim = json.load(open(path))
    for mine, theirs in zip(trees, sim):
        assert mine['name'] == theirs['name'], (mine['name'], theirs['name'])
        a = [(t['name'], t['row'], t['col'], t['max']) for t in mine['talents']]
        b = [(t['fancyName'], t['location']['rowIdx'], t['location']['colIdx'], t['maxPoints']) for t in theirs['talents']]
        if a != b:
            raise SystemExit(f'{mine["name"]}: Wowhead and the sim disagree\n{a}\n{b}')
    print('trees match the sim')


if __name__ == '__main__':
    main()
